import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const abiDir = join(here, '../../contracts/src/abis');
const output = join(here, '../src/abis.ts');

const camel = (name) => name[0].toLowerCase() + name.slice(1);

function render() {
  const contracts = readdirSync(abiDir)
    .filter((file) => file.endsWith('.json'))
    .sort()
    .map((file) => ({
      key: camel(basename(file, '.json')),
      abi: JSON.parse(readFileSync(join(abiDir, file), 'utf8')),
    }));

  const abis = contracts.map(
    ({ key, abi }) => `export const ${key}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`
  );
  const registry = contracts.map(({ key }) => `  ${key}: ${key}Abi,`).join('\n');

  return [
    '// Generated by scripts/generate-abis.mjs from packages/contracts/src/abis. Do not edit.\n',
    ...abis,
    `export const ABIS = {\n${registry}\n} as const;\n`,
    'export type ContractName = keyof typeof ABIS;\n',
  ].join('\n');
}

const generated = render();

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    console.error('src/abis.ts is out of date: run `yarn workspace @repo/shared generate:abis`');
    process.exit(1);
  }
} else {
  writeFileSync(output, generated);
  console.log(`Generated ${output}`);
}
